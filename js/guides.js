/** فحص وعرض بطاقة الشرح الأول للقسم (تظهر لأول مرة فقط) */
export async function checkSectionIntro(app, tabId, root) {
  if (!root) return;
  const guide = SECTION_GUIDES[tabId];
  if (!guide) return;

  // فحص هل شاهد المستخدم الشرح من قبل
  const seenKey = 'intro_seen_' + tabId;
  const isSeen = await app.store.getMeta(seenKey, false);
  if (isSeen) return;

  // التحقق من عدم تكرار إضافة البطاقة
  if (root.querySelector(`.tab-intro-card[data-tab="${tabId}"]`)) return;

  const closeBtn = btn('فهمت، إخفاء الشرح ✓', {
    cls: 'primary sm',
    onclick: async () => {
      haptic('success');
      await app.store.setMeta(seenKey, true);
      card.style.transition = 'opacity .2s, transform .2s';
      card.style.opacity = '0';
      card.style.transform = 'translateY(-8px)';
      setTimeout(() => card.remove(), 220);
    },
  });

  const tipsList = h('ul.tab-intro-tips', guide.tips.map((t) => h('li', t)));

  const card = h('div.tab-intro-card', { dataset: { tab: tabId } },
    h('div.tab-intro-head',
      h('div.tab-intro-titles',
        h('h3', guide.title),
        h('p', guide.desc))),
    tipsList,
    h('div.tab-intro-foot', closeBtn)
  );

  // إدراج البطاقة في أعلى المحتوى قبل البطاقات الأخرى
  const firstChild = root.firstChild;
  if (firstChild) root.insertBefore(card, firstChild);
  else root.append(card);
}

/** إعادة تعيين شروحات الأقسام لظهورها مجدداً */
export async function resetSectionIntros(app) {
  for (const tabId of Object.keys(SECTION_GUIDES)) {
    await app.store.setMeta('intro_seen_' + tabId, false);
  }
  toast('أُعيد تفعيل شروحات الأقسام للأول مرة ✔', 'ok');
}

/** نافذة دليل الاستخدام الشامل لمزايا وشرح كل قسم */
export function openUserGuide(app) {
  haptic('light');
  sheet('دليل الاستخدام ومزايا تطبيق حذيفة', (close) => {
    const list = h('div', { style: { display: 'flex', flexDirection: 'column', gap: '14px', maxHeight: '72vh', overflowY: 'auto', padding: '4px 2px' } });

    // ترويسة تعريفية
    list.append(h('div.card',
      h('h2', 'مرحباً بك في «حذيفة» 👁️✋'),
      h('p.sub', 'منصة ذكية متكاملة تجمع تقنيات الذكاء الاصطناعي لمساعدة مجتمع الصم، ضعاف السمع، والمكفوفين، بدون إعلانات وتعمل بأمان داخل جهازك.')
    ));

    // بطاقة وثيقة وورقة عمل النظارة الذكية للمكفوفين
    list.append(h('div.card', { style: { borderInlineStart: '4px solid #38bdf8', background: 'rgba(56, 189, 248, 0.08)' } },
      h('div.row.between',
        h('h3', '👓 وثيقة وورقة عمل النظارة الذكية'),
        btn('فتح الوثيقة ↗', {
          cls: 'primary sm',
          onclick: () => {
            window.open('docs/smart_glasses_project_sheet.html', '_blank');
          },
        })),
      h('p.small.muted', 'المخطط الهندسي الكامل، الكود المصدري للفيرموير والبلوتوث (BLE)، مخطط التوصيل الكهربائي، وملفات الطباعة ثلاثية الأبعاد.')
    ));

    // بطاقة الحركات والإيماءات السريعة
    list.append(h('div.card',
      h('h3', '📱 إيماءات الموبايل السريعة'),
      h('ul.tab-intro-tips',
        h('li', 'السحب لليمين/اليسار: التنقل السلس بين أقسام التطبيق بحركة واحدة.'),
        h('li', 'نقرتان على الكاميرا (Double-tap): قلب الكاميرا فورياً بين الأمامية والخلفية.'),
        h('li', 'وضع الشاشة المعتمة (OLED): في قسم الرادار لتوفير 70% من بطارية الهاتف.'),
        h('li', 'فقاعة الطوارئ العائمة (⚠): اضغطها في أي وقت لإطلاق استغاثة وإرسال موقعك.')
      )
    ));

    // أقسام التطبيق بالتفصيل
    for (const [id, g] of Object.entries(SECTION_GUIDES)) {
      const tipsUl = h('ul.tab-intro-tips', g.tips.map((t) => h('li', t)));
      const secCard = h('div.card', { style: { borderInlineStart: `4px solid ${g.color || 'var(--accent)'}` } },
        h('div.row.between',
          h('h3', g.title),
          btn('افتح القسم', {
            cls: 'ghost sm',
            onclick: () => {
              close();
              app.go(id);
            },
          })),
        h('p.small.muted', g.desc),
        tipsUl
      );
      list.append(secCard);
    }

    // زر إعادة تفعيل الشروحات للأول مرة
    const resetBtn = btn('إعادة تفعيل رسائل الشرح عند فتح الأقسام', {
      cls: 'ghost sm',
      onclick: async () => {
        await resetSectionIntros(app);
      },
    });

    const foot = h('div.row.between', { style: { marginTop: '10px' } },
      resetBtn,
      btn('إغلاق الدليل', { cls: 'primary', onclick: close })
    );

    list.append(foot);
    return list;
  });
}
